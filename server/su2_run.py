"""Orchestrates an actual SU2 pulsatile CFD run: writes the mesh/.cfg/
params files a run needs, launches su2_pulsatile_runner.py under mpirun
as a background subprocess, and parses its stdout progress lines to drive
a per-side job dict the app can poll (same role as app.py's existing
su2_mesh_jobs background-thread pattern, one level up — this is the step
that actually solves the physics on the mesh that pipeline already
builds).

SU2/pysu2 install location, numerics and fluid-property defaults are
carried over unchanged from the validated standalone pipeline
(~/Desktop/SU2 Pipeline Code/*/pulsatile.cfg and project memory
su2_carotid_hemodynamics_pipeline.md) — only the per-patient physiological
values (server/app.py's SU2ParamsRequest) vary run to run; see that
memory file for why each fixed numeric choice was made (INC_NONDIM=
DIMENSIONAL, CFL=1 first-order for stability, etc).
"""
import json
import logging
import os
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path

from .config import SU2_BIN_DIR, MPI_PYTHON

import numpy as np

from . import su2_export

log = logging.getLogger("carotid_server")

RUNNER_SCRIPT = str(Path(__file__).resolve().parent / "su2_pulsatile_runner.py")

# Run for this many cardiac cycles — matches the number the standalone
# pipeline's own real runs used (reaches periodic near-steady-state within
# this with the small Windkessel compliance calibrate_two_outlet_rcr uses
# by default; see that module's own docstring). TIME_STEP_S/INNER_ITER/
# CFL_NUMBER/fluid properties are likewise carried over unchanged from
# every validated real run in that pipeline.
N_CARDIAC_CYCLES = 2
TIME_STEP_S = 0.005
INNER_ITER = 20
CFL_NUMBER = 1.0
FLUID_DENSITY_KG_M3 = 1050.0
FLUID_VISCOSITY_PAS = 0.0035
MMHG_TO_PA = 133.322


def mpi_processes() -> int:
    # Multi-rank OpenMPI on macOS has repeatedly hung in MPI_Win_create
    # even with osc=sm. Prefer one rank locally; operators can override.
    override = os.environ.get("CAROTID_MPI_N")
    if override:
        return max(1, int(override))
    if sys.platform == "darwin":
        return 1
    return max(1, min(8, os.cpu_count() or 4))


def _cfg_text(mesh_filename: str, time_iter: int, edv_cms: float, inlet_direction) -> str:
    # MARKER_INLET's velocity/direction here are placeholders SU2 needs
    # at startup only — su2_pulsatile_runner.py overrides both every
    # physical time step via SetMarkerCustomInletFlow*, so these numbers
    # never actually drive the solve; a reasonable diastolic-ish start
    # just avoids beginning from a wildly wrong state.
    placeholder_v_ms = max(edv_cms, 1.0) / 100.0
    dx, dy, dz = (float(c) for c in inlet_direction)
    return f"""% Auto-generated by carotid-segmentation's su2_run.py — pulsatile
% incompressible laminar Newtonian flow. Inlet velocity and outlet
% (Windkessel) pressure are overridden every physical time step by
% su2_pulsatile_runner.py via the SU2 Python wrapper; the MARKER_INLET
% values below are just the static placeholders SU2 needs at startup.

SOLVER= INC_NAVIER_STOKES
KIND_TURB_MODEL= NONE
MATH_PROBLEM= DIRECT
RESTART_SOL= NO

% ---- fluid model: Newtonian blood ----
INC_DENSITY_MODEL= CONSTANT
INC_ENERGY_EQUATION= NO
INC_NONDIM= DIMENSIONAL
INC_DENSITY_INIT= {FLUID_DENSITY_KG_M3}
INC_VELOCITY_INIT= (0.0, 0.0, 0.0)
FLUID_MODEL= CONSTANT_DENSITY
VISCOSITY_MODEL= CONSTANT_VISCOSITY
MU_CONSTANT= {FLUID_VISCOSITY_PAS}

% ---- boundary markers (tag names match this app's own ModelFaceID map) ----
MARKER_HEATFLUX= ( wall, 0.0 )
MARKER_INLET= ( cca_inlet, 293.0, {placeholder_v_ms:.6f}, {dx:.6f}, {dy:.6f}, {dz:.6f} )
MARKER_OUTLET= ( ica_outlet, 0.0, eca_outlet, 0.0 )
INC_INLET_TYPE= VELOCITY_INLET
INC_OUTLET_TYPE= PRESSURE_OUTLET PRESSURE_OUTLET

% ---- unsteady (pulsatile) settings ----
TIME_DOMAIN= YES
TIME_STEP= {TIME_STEP_S}
TIME_MARCHING= DUAL_TIME_STEPPING-2ND_ORDER
TIME_ITER= {time_iter}
INNER_ITER= {INNER_ITER}

% ---- numerics ----
NUM_METHOD_GRAD= GREEN_GAUSS
CFL_NUMBER= {CFL_NUMBER}
CONV_NUM_METHOD_FLOW= FDS
MUSCL_FLOW= NO
SLOPE_LIMITER_FLOW= NONE
TIME_DISCRE_FLOW= EULER_IMPLICIT
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_PREC= ILU
LINEAR_SOLVER_ERROR= 1E-6
LINEAR_SOLVER_ITER= 10
CONV_RESIDUAL_MINVAL= -10
CONV_STARTITER= 0

% ---- mesh / IO ----
MESH_FILENAME= {mesh_filename}
MESH_FORMAT= SU2
TABULAR_FORMAT= CSV
OUTPUT_WRT_FREQ= 10
SCREEN_OUTPUT= (TIME_ITER, INNER_ITER, RMS_PRESSURE, RMS_VELOCITY-X)
OUTPUT_FILES= (RESTART, PARAVIEW)
VOLUME_OUTPUT= (COORDINATES, SOLUTION, PRIMITIVE)
CONV_FILENAME= history
RESTART_FILENAME= restart
SOLUTION_FILENAME= solution
VOLUME_FILENAME= flow
SURFACE_FILENAME= surface_flow
"""


def prepare_run_files(run_dir: Path, vtu_bytes: bytes, vtp_bytes: bytes, face_map: dict,
                       su2_params: dict, inlet_direction, case_name: str):
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)

    mesh_text = su2_export.vtu_vtp_bytes_to_su2_mesh_text(vtu_bytes, vtp_bytes, face_map)
    mesh_path = run_dir / "mesh.su2"
    mesh_path.write_text(mesh_text)

    time_iter = max(10, round(N_CARDIAC_CYCLES * su2_params["cardiac_cycle_s"] / TIME_STEP_S))
    cfg_path = run_dir / "run.cfg"
    cfg_path.write_text(_cfg_text("mesh.su2", time_iter, su2_params["edv_cms"], inlet_direction))

    params = {
        "case_name": case_name,
        "psv_cms": su2_params["psv_cms"],
        "edv_cms": su2_params["edv_cms"],
        "cardiac_cycle_s": su2_params["cardiac_cycle_s"],
        "ica_fraction": su2_params["ica_fraction"],
        "ica_map_pa": su2_params["ica_map_mmhg"] * MMHG_TO_PA,
        "eca_map_pa": su2_params["eca_map_mmhg"] * MMHG_TO_PA,
        "inlet_direction": [float(c) for c in inlet_direction],
    }
    params_path = run_dir / "run_params.json"
    params_path.write_text(json.dumps(params, indent=2))

    return mesh_path, cfg_path, params_path, time_iter


def run_in_background(job: dict, run_dir: Path, cfg_path: Path, params_path: Path):
    """Launches the solver subprocess and updates `job` (the exact dict
    object stored at case.su2_run_jobs[side], mutated in place — same
    cross-thread-visible-dict pattern app.py's su2_mesh_jobs background
    thread already uses) as its stdout reports progress. Meant to be the
    target of its own daemon thread; blocks until the subprocess exits."""
    if job.get('cancel_requested'):
        job['state'] = 'cancelled'
        return
    env = os.environ.copy()
    env["PYTHONPATH"] = SU2_BIN_DIR + os.pathsep + env.get("PYTHONPATH", "")
    # macOS OpenMPI/PMIx: listener bind and RDMA one-sided windows hang
    # without these. Keep any values the operator already exported.
    env.setdefault("OMPI_MCA_btl", "self,tcp")
    env.setdefault("OMPI_MCA_pml", "ob1")
    env.setdefault("OMPI_MCA_osc", "sm")
    env.setdefault("PMIX_MCA_gds", "hash")
    n_procs = mpi_processes()
    cmd = ["mpirun", "-n", str(n_procs), MPI_PYTHON, RUNNER_SCRIPT, str(cfg_path), str(params_path)]
    job["cmd"] = " ".join(cmd)
    job["mpi_processes"] = n_procs

    try:
        proc = subprocess.Popen(
            cmd, cwd=str(run_dir), env=env,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1, start_new_session=True,
        )
    except Exception as e:
        log.exception("failed to launch SU2 solver subprocess")
        job["state"] = "error"
        job["error"] = f"failed to launch solver: {e}"
        return

    job["pid"] = proc.pid
    job["process"] = proc
    if job.get('cancel_requested'):
        cancel_run(job)

    log_path = run_dir / "solver_stdout.log"
    with open(log_path, "w") as log_f:
        for raw_line in proc.stdout:
            log_f.write(raw_line)
            if job.get("state") == "cancelling":
                continue  # drain the pipe so the subprocess doesn't block on a full buffer while it exits
            line = raw_line.strip()
            if line.startswith("SU2PROGRESS "):
                try:
                    info = json.loads(line[len("SU2PROGRESS "):])
                except json.JSONDecodeError:
                    continue
                job.update(info)
                job["state"] = "running"
            elif line.startswith("SU2DONE "):
                try:
                    info = json.loads(line[len("SU2DONE "):])
                except json.JSONDecodeError:
                    info = {}
                job.update(info)
                job["state"] = "done"
            elif line.startswith("SU2ERROR "):
                try:
                    info = json.loads(line[len("SU2ERROR "):])
                except json.JSONDecodeError:
                    info = {"message": line}
                job["state"] = "error"
                job["error"] = info.get("message", "unknown solver error")

    returncode = proc.wait()
    job.pop("process", None)

    if job.get("cancel_requested"):
        job["state"] = "cancelled"
    elif returncode != 0:
        job['state'] = 'error'
        job['error'] = f'solver exited with code {returncode}; see solver_stdout.log'
    elif job.get("state") == "running":
        # Exited without an explicit SU2DONE/SU2ERROR line — a crash,
        # segfault, or an MPI rank dying doesn't necessarily print either.
        if returncode == 0:
            job["state"] = "done"
        else:
            job["state"] = "error"
            job["error"] = f"solver process exited with code {returncode} — see solver_stdout.log"
    job["output_dir"] = str(run_dir)


def start_run(job: dict, run_dir: Path, cfg_path: Path, params_path: Path):
    threading.Thread(target=run_in_background, args=(job, run_dir, cfg_path, params_path), daemon=True).start()


def cancel_run(job: dict):
    job['cancel_requested'] = True
    proc = job.get('process')
    if proc is None or proc.poll() is not None:
        if job.get('state') == 'running':
            job['state'] = 'cancelled'
        return False
    job['state'] = 'cancelling'
    try:
        os.killpg(proc.pid, signal.SIGTERM)
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    except ProcessLookupError:
        pass
    return True
